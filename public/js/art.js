/* ---------- tiny shape helpers ---------- */
const P = (d, f, e = '') => `<path d="${d}" fill="${f}" ${e}/>`;
const L = (d, s, w = 2, e = '') =>
  `<path d="${d}" fill="none" stroke="${s}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round" ${e}/>`;
const C = (x, y, r, f, e = '') => `<circle cx="${x}" cy="${y}" r="${r}" fill="${f}" ${e}/>`;
const E = (x, y, rx, ry, f, e = '') => `<ellipse cx="${x}" cy="${y}" rx="${rx}" ry="${ry}" fill="${f}" ${e}/>`;
const G = (c, s) => `<g class="${c}">${s}</g>`;
const mir = (s) => `<g transform="matrix(-1 0 0 1 100 0)">${s}</g>`;
const both = (s) => s + mir(s);
const rot = (a, x, y) => `transform="rotate(${a} ${x} ${y})"`;
const rim = (c, w = 1.2) => `stroke="${c}" stroke-width="${w}" stroke-linejoin="round"`;
const op = (o) => `opacity="${o}"`;

const rg = (k, c) =>
  `<radialGradient id="nd${U}${k}"><stop offset="0" stop-color="${c}" stop-opacity=".85"/><stop offset="1" stop-color="${c}" stop-opacity="0"/></radialGradient>`;
/** night sky: vertical gradient a->b, plus glow gradients g (and optional h) */
const sky = (a, b, g = '#f6efc9', h) =>
  `<defs><linearGradient id="nd${U}s" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${a}"/><stop offset="1" stop-color="${b}"/></linearGradient>${rg('g', g)}${h ? rg('h', h) : ''}</defs><rect width="100" height="100" fill="url(#nd${U}s)"/>`;
const glow = (x, y, r, o = 1, k = 'g', cls = '') =>
  `<circle cx="${x}" cy="${y}" r="${r}" fill="url(#nd${U}${k})" opacity="${o}"${cls ? ` class="${cls}"` : ''}/>`;
const moon = (x, y, r, c = '#f6efc9', k = 'g') =>
  glow(x, y, r * 2.4, 0.55, k) + C(x, y, r, c) + C(x - r * 0.3, y - r * 0.25, r * 0.22, '#000', op(0.08));
/** many round dots as ONE path: s = "x y x y …", w = dot diameter */
const dots = (s, c, w, e = '') => L(s.replace(/(\S+) (\S+) ?/g, 'M$1 $2h.01'), c, w, e);
const stars = (s) => dots(s, '#fff', 1.6, op(0.75));
const mist = (y, c = '#cfe3f5', o = 0.16) => E(28, y, 50, 7, c, op(o)) + E(76, y + 5, 46, 6, c, op(o));
/** glowing spirit eyes: halo + iris (+ pupil) */
const eyes = (x1, x2, y, r, c = '#ffe66d', p = '#1a1020', dx = 0, dy = 0) =>
  G(
    'a-blink',
    C(x1, y, r, c, `stroke="${c}" stroke-opacity=".28" stroke-width="${+(r * 1.4).toFixed(1)}"`) +
      C(x2, y, r, c, `stroke="${c}" stroke-opacity=".28" stroke-width="${+(r * 1.4).toFixed(1)}"`) +
      (p ? C(x1 + dx, y + dy, r * 0.45, p) + C(x2 + dx, y + dy, r * 0.45, p) : '')
  );
/** four-point sparkle */
const spark = (x, y, r, f = '#ffd166') =>
  P(`M${x} ${y - r}Q${x} ${y} ${x + r} ${y}Q${x} ${y} ${x} ${y + r}Q${x} ${y} ${x - r} ${y}Q${x} ${y} ${x} ${y - r}Z`, f);

